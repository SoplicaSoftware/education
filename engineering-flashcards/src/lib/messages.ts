/** Polish plural: 1 karta, 2–4 karty, 5+ kart (12–14 also take the last form). */
function plPlural(n: number, one: string, few: string, many: string) {
  if (n === 1) return `1 ${one}`
  const tens = n % 100
  const units = n % 10
  return `${n} ${units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? few : many}`
}

